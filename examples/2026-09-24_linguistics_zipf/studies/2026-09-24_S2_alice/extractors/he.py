def _read(path):
    with open(path, 'rb') as f:
        t = f.read().decode('utf-8')
    return t.replace('\r\n', '\n').replace('\r', '\n')


def _split_notes(lines):
    """Отделяет блок сносок и колофон: возвращает строки книги; блок сносок проверяется."""
    first = next(i for i, ln in enumerate(lines) if '↩︎' in ln)
    start = first
    while lines[start - 1].strip():        # сноска может занимать несколько строк: к началу её блока
        start -= 1
    blocks, cur = [], []
    for ln in lines[start:] + ['']:
        if ln.strip():
            cur.append(ln.strip())
        elif cur:
            blocks.append(cur)
            cur = []
    notes = [b for b in blocks if b[-1].endswith('&nbsp;↩︎')]
    rest = [b for b in blocks if not b[-1].endswith('&nbsp;↩︎')]
    assert len(notes) == N_NOTES, f'he: сносок {len(notes)}, ожидалось {N_NOTES}'
    assert len(rest) == 1 and rest[0][0].startswith('את הטקסט[ים] לעיל הפיקו מתנדבי פרויקט בן־יהודה'), \
        'he: в блоке сносок есть что-то кроме сносок и колофона'
    assert blocks[-1] is rest[0], 'he: колофон не последний'
    return lines[:start]


def _clean(body):
    """Тело главы: строки без концевых пробелов, не больше одной пустой строки подряд."""
    t = '\n'.join(ln.strip() for ln in body.split('\n'))
    t = re.sub(r'\n{3,}', '\n\n', t)
    return t.strip('\n')


def chapters(paths):
    lines = _split_notes(_read(paths[0]).split('\n'))
    # иллюстрации и подписи к ним
    images = [i for i, ln in enumerate(lines) if IMAGE.match(ln.strip())]
    assert len(images) == N_IMAGES, f'he: иллюстраций {len(images)}, ожидалось {N_IMAGES}'
    caps = []
    for c in CAPTIONS:
        where = [i for i, ln in enumerate(lines) if ln.strip() == c]
        assert len(where) == 1, f'he: подпись {c!r} найдена {len(where)} раз'
        caps.append(where[0])
    assert caps == sorted(caps), 'he: подписи идут не в том порядке'
    drop = set(images) | set(caps)
    t = '\n'.join(ln for i, ln in enumerate(lines) if i not in drop)
    # маркеры сносок: строго 1…142 по порядку; остальные цифры — только настоящие числа
    marks = [int(m.group()) for m in MARK.finditer(t)]
    assert marks == list(range(1, N_NOTES + 1)), 'he: маркеры сносок идут не подряд'
    t = MARK.sub('', t)
    assert re.findall(r'\d+', t) == REAL_NUMBERS, f'he: лишние цифры {re.findall(r"[0-9]+", t)}'
    if not KEEP_FRENCH_GLOSS:
        assert t.count(GLOSS) == 1, 'he: глосса «איה החתול שלי?» не найдена'
        t = t.replace(GLOSS, '')
    assert t.count(TAIL_BREAK[0]) == 1, 'he: разрыв «רב־/זנובא» в хвосте Мыши не найден'
    t = t.replace(*TAIL_BREAK)
    # главы
    heads = list(HEAD.finditer(t))
    assert [h.group(1) for h in heads] == ORD, f'he: заголовки {[h.group(1) for h in heads]}'
    assert [h.group(2) and h.group(2).strip() for h in heads] == TITLES, 'he: названия глав не совпали'
    assert t[:heads[0].start()].strip() == BOOK_TITLE, 'he: перед главой I не только название книги'
    ends = [h.start() for h in heads[1:]] + [len(t)]
    res = [_clean(t[h.end():e]) for h, e in zip(heads, ends)]
    # Сверка границ по содержанию: первая и последняя фразы книги (как в английском:
    # «Alice was beginning to get very tired of sitting by her sister» … «the happy summer days»)
    assert res[0].startswith('נלאתה עליסה הקטנה לשבת ליד אחותה'), 'he: начало главы I'
    assert res[-1].endswith('ימים טובים, ימי קיץ ושמש – ארכים,\nנוהרים, מלאים גיל ואשר.'), 'he: конец главы XII'
    return res
