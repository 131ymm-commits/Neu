"""bg — болгарский перевод с chitanka.info, файл bg_00 (формат SFB), UTF-8, LF.
Файл начинается прямо с главы I и кончается последней фразой главы XII: титула, оглавления,
вступительного стихотворения, предисловия, послесловия и блока сносок в нём нет.
Разметка SFB (первое поле строки до табуляции):
- «>\\t…» — заголовок: у каждой главы две такие строки подряд, «ПЪРВА ГЛАВА» … «ДВАНАДЕСЕТА ГЛАВА»
  и название («В ЗАЕШКАТА ДУПКА» …) — обе отбрасываются;
- «\\t…» — абзац текста: табуляция снимается;
- «P>» / «P$» — начало и конец стихотворения (6 стихов внутри глав), «C>» / «C$» — центрированный блок
  (письмо Алисы своей ноге, глава II) — строки-маркеры отбрасываются, стихи и письмо остаются;
- «@\\t…» — подпись внутри центрированного блока («(От неговата Алиса)» — «(with Alice's love)» у Кэрролла):
  метка снимается, текст остаётся.
Строк «|\\t», «#», сносок «[N]» в файле нет (проверяется).
Глосса переводчика: после французской фразы «Оu est ma chatte?» (глава II) стоит перевод в скобках
«(Де е моята котка?)» — у Кэрролла его нет, это пояснение переводчика; снимается (KEEP_FRENCH_GLOSS).
В «Оu» первая буква — кириллическая «О» (опечатка источника), не правится."""
import re

ORD = ['ПЪРВА', 'ВТОРА', 'ТРЕТА', 'ЧЕТВЪРТА', 'ПЕТА', 'ШЕСТА', 'СЕДМА', 'ОСМА', 'ДЕВЕТА', 'ДЕСЕТА',
       'ЕДИНАДЕСЕТА', 'ДВАНАДЕСЕТА']
# Названия глав, как они стоят в заголовках — сверка по содержанию, а не только по номеру
TITLES = ['В ЗАЕШКАТА ДУПКА', 'ВАДАТА НА СЪЛЗИТЕ', 'СВОБОДНО НАДБЯГВАНЕ И ЕДНА ДЪЛГА ИСТОРИЯ',
          'ЗАЕКА ИЗПРАЩА ЕДНО ПЕРЦЕ', 'СЪВЕТЪТ НА ЕДНА ГЪСЕНИЦА', 'ПРАСЕ И ПИПЕР',
          'ЕДНА НЕОБИКНОВЕНА ЗАКУСКА', 'ЦАРИЦАТА И НЕЙНОТО ИГРИЩЕ', 'ИСТОРИЯТА НА ЛИГАВАТА КОСТЕНУРКА',
          'ТАНЦЪТ НА МОРСКИТЕ РАЦИ', 'КОЙ ОТКРАДНА БАНИЧКИТЕ?', 'ПОКАЗАНИЯТА НА АЛИСА']
# Заголовок главы: две строки «>\t<порядковое> ГЛАВА» и «>\t<название>»
HEAD = re.compile(r'^>\t(%s) ГЛАВА\n>\t(.+)$' % '|'.join(ORD), re.M)
BLOCK_MARK = re.compile(r'^[PC][>$]$')   # начало/конец стихотворения (P) или центрированного блока (C)
# Перевод французской фразы переводчиком — не текст Кэрролла; True оставляет его
KEEP_FRENCH_GLOSS = False
GLOSS = ' (Де е моята котка?)'


def _read(path):
    with open(path, 'rb') as f:
        t = f.read().decode('utf-8')
    return t.replace('\r\n', '\n').replace('\r', '\n')


def _clean(body):
    """Тело главы: снять разметку SFB; абзацы — отдельные строки, строфы разделены пустой строкой."""
    out = []
    for line in body.split('\n'):
        if BLOCK_MARK.match(line):
            continue
        if line.startswith('@\t'):         # подпись в центрированном блоке — текст книги
            line = line[2:]
        assert not re.match(r'[>|#@]', line), f'bg: необработанная строка SFB {line!r}'
        out.append(line.strip())            # снимает табуляцию-отступ абзаца
    t = '\n'.join(out)
    t = re.sub(r'\n{3,}', '\n\n', t)       # не больше одной пустой строки подряд
    return t.strip('\n')


def chapters(paths):
    t = _read(paths[0])
    assert not re.search(r'\[\d+\]', t), 'bg: найдены сноски [N]'
    if not KEEP_FRENCH_GLOSS:
        assert t.count(GLOSS) == 1, 'bg: глосса «Де е моята котка?» не найдена'
        t = t.replace(GLOSS, '')
    heads = list(HEAD.finditer(t))
    assert [h.group(1) for h in heads] == ORD, f'bg: заголовки {[h.group(1) for h in heads]}'
    assert [h.group(2).strip() for h in heads] == TITLES, 'bg: названия глав не совпали'
    assert not t[:heads[0].start()].strip(), 'bg: перед главой I есть текст'
    # Конец главы XII — конец файла (после последней фразы книги ничего нет)
    ends = [h.start() for h in heads[1:]] + [len(t)]
    res = [_clean(t[h.end():e]) for h, e in zip(heads, ends)]
    # Сверка границ по содержанию: первая и последняя фразы книги (как в английском)
    assert res[0].startswith('Алиса се умори да седи без работа до сестра си на скамейката'), 'bg: начало'
    assert res[-1].endswith('като си спомня за своето детство и за щастливите летни дни.'), 'bg: конец'
    return res
