"""ja — S-19, Аодзора-бунко №57320 «アリスはふしぎの国で», пер. Окубо Ю (大久保ゆう, 2015), файл ja_00.txt.
Кодировка проверена: UTF-8 без BOM (декодируется строго; Shift_JIS не нужен), CRLF.
Разметка Аодзоры (ruby-версия файла):
* титул (название, автор, переводчик), легенда знаков «【テキスト中に現れる記号について】» между рядами «-----»;
* стихотворное посвящение «ぜんぶ　きんきら　ごごのこと…» ДО главы 1 — пролог, снимается (правило PLAN);
* заголовок главы — одна строка «［＃４字下げ］１　ひゅうんとウサギ穴へ［＃「１　ひゅうんとウサギ穴へ」は中見出し］»
  (номера １…９ полноширинные, 10…12 обычные), перед ним «［＃改ページ］»;
* после главы 12 — «［＃改丁］», затем письмо Кэрролла «『アリスはふしぎの国で』を読んでくれた子どものみなさんへ»
  (Рождество 1871), «訳者あとがき» (девять частей) и библиографический блок Аодзоры после «［＃本文終わり］».
  Всё это снимается: книга кончается на «［＃改丁］» (проверяется, что за ним идёт именно письмо к детям).
Внутри глав снимается:
* примечания набора ［＃…］: «［＃改ページ］», «［＃ここから３字下げ］»/«［＃ここで字下げ終わり］» (отступы у стихов),
  «［＃６字下げ］» и т. п. в начале строки (сам текст строки остаётся: «コーラス», «「わう！　わう！　わう！」»),
  «［＃挿絵N（fig57320_NN.png…）入る］» (иллюстрации, всегда отдельной строкой), «［＃「…」に傍点］» (точки выделения);
* руби 《…》 — чтение над иероглифом (階段《かいだん》 → 階段); знак ｜ (начало базы руби) в файле не встречается,
  но снимается тоже;
* ряды звёздочек «＊　　　＊　　　＊» (три строки; в главе 1 дважды, в главе 5 один раз) — типографский разделитель,
  как ряд «*  *  *» в английском.
Остаётся всё прочее: стихи и песни внутри глав (в т. ч. хвост Мыши в главе 3 — фигурный набор, строки как в
файле), «※くり返し！» в главе 10 (реплика Грифона «Chorus again!», знак ※ — часть текста перевода),
полноширинные цифры, 〈…〉 (надписи: 〈タベテ〉 и т. п.). Сносок и примечаний переводчика внутри глав нет."""
import re

# Номера и названия глав, как в заголовках файла (сверка по содержанию, а не только по номеру)
NUMS = ['１', '２', '３', '４', '５', '６', '７', '８', '９', '10', '11', '12']
TITLES = ['ひゅうんとウサギ穴へ', 'なみだまり', 'ドードーめぐりで長々しっぽり', 'ウサギ、ビルくんをさしむける',
          '青虫の教え', 'ブタとコショウ', 'おかしなお茶会', 'クイーンさまのクローケー場',
          'ウミガメフーミのものがたり', 'ロブスターのカドリール', 'だあれがタルトをぬすんだの', 'アリスがわけを語る']
HEAD = re.compile(r'^［＃４字下げ］(\S+)　(.+?)［＃「\1　\2」は中見出し］$', re.M)
# Конец книги: «［＃改丁］», за которым письмо Кэрролла к детям (снимается вместе со всем дальнейшим)
BOOK_END = re.compile(r'^［＃改丁］\n+［＃４字下げ］『アリスはふしぎの国で』を読んでくれた子どものみなさんへ', re.M)
NOTE = re.compile(r'［＃[^］]*］')          # любое примечание набора Аодзоры
RUBY = re.compile(r'《[^》]*》')            # чтение руби
STARS = re.compile(r'^[＊　 ]+$')        # строка из звёздочек и пробелов
N_STAR_LINES = 9                             # 3 разделителя по 3 строки


def _read(path):
    with open(path, 'rb') as f:
        t = f.read().decode('utf-8')         # строго: ошибка, если файл окажется не в UTF-8
    return t.replace('\r\n', '\n').replace('\r', '\n')


def _clean(body):
    """Тело главы без разметки Аодзоры; строки без концевых пробелов, не больше одной пустой строки подряд."""
    out, stars = [], 0
    for line in body.split('\n'):
        if STARS.match(line) and '＊' in line:
            stars += 1
            continue
        s = NOTE.sub('', line)
        if not s.strip() and line.strip():   # строка состояла только из примечаний набора
            continue
        out.append(s.rstrip())
    t = '\n'.join(out)
    t = RUBY.sub('', t).replace('｜', '')
    t = re.sub(r'\n{3,}', '\n\n', t)
    return t.strip('\n'), stars


def chapters(paths):
    t = _read(paths[0])
    end = BOOK_END.search(t)
    assert end, 'ja: не найден конец книги (［＃改丁］ перед письмом к детям)'
    assert '訳者あとがき' in t[end.start():] and '訳者あとがき' not in t[:end.start()], 'ja: послесловие не после книги'
    heads = list(HEAD.finditer(t, 0, end.start()))
    assert [h.group(1) for h in heads] == NUMS, f'ja: номера глав {[h.group(1) for h in heads]}'
    assert [h.group(2) for h in heads] == TITLES, 'ja: названия глав не совпали'
    ends = [h.start() for h in heads[1:]] + [end.start()]
    res, stars = [], 0
    for h, e in zip(heads, ends):
        c, n = _clean(t[h.end():e])
        res.append(c)
        stars += n
    assert stars == N_STAR_LINES, f'ja: строк-разделителей из звёздочек {stars}, ожидалось {N_STAR_LINES}'
    for k, c in enumerate(res, 1):
        for bad in ('［', '］', '＃', '《', '》', '｜'):
            assert bad not in c, f'ja: в главе {k} осталась разметка {bad!r}'
    # Сверка границ по содержанию: первая и последняя фразы книги
    # («Alice was beginning to get very tired of sitting by her sister…» … «…and the happy summer days.»)
    assert res[0].startswith('　アリスはあっきあきしてきた、木かげで、お姉さまのそばですわってるのも'), 'ja: начало главы 1'
    assert res[-1].endswith('自分の子ども時代の思い出、あの幸せな夏の日々に。'), 'ja: конец главы 12'
    return res
