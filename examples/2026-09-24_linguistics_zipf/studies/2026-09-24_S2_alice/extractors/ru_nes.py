"""ru_nes — S-15, русский перевод (по метке корпуса — Нестеренко), файл ru_nes_00.txt
(iglika88/corpus_original_and_abridged_texts, «aw ru full 2»). UTF-8, CRLF.
Текст вынут из PDF: каждая строка печатной страницы — отдельная строка, между строками пустая строка;
границы абзацев потеряны (для подсчёта слов они не нужны, строки сохраняются как есть).
До главы I и после главы XII ничего нет: файл начинается заголовком «Глава I. …» и кончается
последней фразой книги. Заголовок главы — одна строка «Глава I. Вниз по кроличьей норе»;
в главе X номер набран кириллической «Х» («Глава Х. Омаровая кадриль»).
Удаляется:
- заголовки глав;
- сноски переводчика: тексты сносок в файле уже вырезаны составителем корпуса, остались
  метки в тексте «[ 2]», «[ 4 ]» (одна разорвана переносом строки: «[» / «28]») и номера сносок
  внизу страницы — строки из одних цифр («2», «3» …); номер «10» прилип к концу строки
  «…побежала туда, 10» — снимается отдельно (FOOTNOTE_NUM_GLUED).
Перенос: в файле один дефис на конце строки — «лишь бы к столу п-» / «одали этот красивый суп?»
(переводчик повторяет разрыв слова Кэрролла «two p / ennyworth»); слово склеивается («подали»),
как и в английском PG, где «Pennyworth» напечатано целиком.
Растянутые слоги песен («Кра-а-а-сивый», «Е-э-да ве-э-э-черняя») — настоящие дефисы, остаются.
Опечатки источника («Qu est ma chante?», «хорощие», «трю дюйма») не правятся."""
import re

ROMAN = ['I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII']
# Названия глав — сверка заголовков по содержанию
TITLES = ['Вниз по кроличьей норе', 'Озеро слез', 'Предвыборный марафон и длинная история',
          'Как маленький Билл чуть не разбиллся', 'Совет гусеницы', 'Поросенок и перец',
          'Безумное чаепитие', 'Крокет Королевы', 'Рассказ Якобы Черепахи', 'Омаровая кадриль',
          'Кто украл торты?', 'Показания Алисы']
# «Глава <римское>. <название>»; в номере допускается кириллическая Х (глава X)
HEAD = re.compile(r'^Глава ([IVXХ]+)\. (.+)$', re.M)
# Метка сноски «[ 12]», «[ 4 ]», в т. ч. разорванная переводом строки «[\n28]»; с пробелом перед ней
MARK = re.compile(r' ?\[\s*\d+\s*\]')
# Номер сноски внизу страницы — строка из одних цифр
FOOTNOTE_NUM = re.compile(r'^\d+$')
# Номер сноски, приклеенный к концу строки текста (один случай)
FOOTNOTE_NUM_GLUED = ('побежала туда, 10', 'побежала туда,')


def _read(path):
    with open(path, 'rb') as f:
        t = f.read().decode('utf-8-sig')
    return t.replace('\r\n', '\n').replace('\r', '\n')


def _clean(body):
    """Тело главы: без пустых строк, меток и номеров сносок; строки PDF соединены через \\n."""
    lines = [l.rstrip() for l in body.split('\n') if l.strip()]
    t = '\n'.join(lines)
    t = MARK.sub('', t)
    lines = [l for l in t.split('\n') if not FOOTNOTE_NUM.match(l.strip())]
    t = '\n'.join(lines)
    if FOOTNOTE_NUM_GLUED[0] in t:
        t = t.replace(FOOTNOTE_NUM_GLUED[0], FOOTNOTE_NUM_GLUED[1])
    # Слово, разорванное дефисом на конце строки («п-» / «одали»), склеивается без дефиса
    t, n = re.subn(r'([^\W\d_])-\n([а-яё])', r'\1\2', t)
    assert '[' not in t and ']' not in t, 'ru_nes: осталась метка сноски'
    return t.strip('\n'), n


def chapters(paths):
    t = _read(paths[0])
    heads = list(HEAD.finditer(t))
    nums = [h.group(1).replace('Х', 'X') for h in heads]  # кириллическая Х -> латинская X
    assert nums == ROMAN, f'ru_nes: заголовки {nums}'
    assert [h.group(2).strip() for h in heads] == TITLES, 'ru_nes: названия глав не совпали'
    assert not t[:heads[0].start()].strip(), 'ru_nes: перед главой I есть текст'
    ends = [h.start() for h in heads[1:]] + [len(t)]
    res, joins = [], 0
    for h, e in zip(heads, ends):
        c, n = _clean(t[h.end():e])
        res.append(c)
        joins += n
    assert joins == 1, f'ru_nes: склеек переноса {joins}, ожидалась 1 («п-одали»)'
    assert 'побежала туда, 10' not in '\n'.join(res)
    # Сверка границ по содержанию: первая и последняя фразы книги (как в английском)
    assert res[0].startswith('Алисе начинало уже надоедать сидеть с сестрой на берегу')
    assert res[-1].endswith('вспоминая собственное детство и счастливые летние дни.')
    return res
