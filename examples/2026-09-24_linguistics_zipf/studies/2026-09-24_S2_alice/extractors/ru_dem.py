# «Мартовский З аяВ», «З аяИ», «З аяН», «З аяЦ», «З аяЯ», «З аяй» — всё это «Заяц»
OCR_HARE = (re.compile(r'З ая[ВИНЦЯй]'), 'Заяц', 12)
# Отбитая заглавная «З» (разрядка): «З начит», «З ачем», «З ато», «З а ними» … — в тексте перевода
# отдельного слова «З» нет, поэтому «З » перед строчной буквой всегда склеивается
OCR_Z = (re.compile(r'(?<![^\W\d_])З (?=[а-яё])'), 'З', 17)


def _read(path):
    with open(path, 'rb') as f:
        t = f.read().decode('utf-8-sig')
    return t.replace('\r\n', '\n').replace('\r', '\n')


def _is_break(s):
    """Разрыв страницы: номер страницы, колонтитул или заголовок главы."""
    return bool(PAGE_NUM.match(s) or RUN_HEAD.match(s) or CHAP.match(s))


def _drop_commentary(lines):
    """Выбрасывает блоки комментария: от начала блока до ближайшего разрыва страницы."""
    text = '\n'.join(lines)
    starts = {}  # номер строки -> позиция начала блока в строке
    offs, o = [], 0
    for l in lines:
        offs.append(o)
        o += len(l) + 1
    for a in COMMENTARY:
        assert text.count(a) == 1, f'ru_dem: начало комментария «{a[:30]}» встречается {text.count(a)} раз'
        p = text.index(a)
        k = max(i for i, off in enumerate(offs) if off <= p)
        starts[k] = p - offs[k]
    out, skip = [], False
    for k, l in enumerate(lines):
        if _is_break(l.strip()):
            skip = False
        elif k in starts:
            skip = True
            if starts[k]:
                out.append(l[:starts[k]])  # перевод до начала комментария в той же строке
            continue
        if not skip:
            out.append(l)
    return out


def _sub(t, bad, good, n):
    """Замена строки с проверкой числа вхождений."""
    assert t.count(bad) == n, f'ru_dem: «{bad}» встречается {t.count(bad)} раз, ожидалось {n}'
    return t.replace(bad, good)


def _resub(t, rule):
    """Замена по регулярному выражению с проверкой числа вхождений."""
    pat, good, n = rule
    t, k = pat.subn(good, t)
    assert k == n, f'ru_dem: {pat.pattern} — {k} вхождений, ожидалось {n}'
    return t


def chapters(paths):
    lines = [l.rstrip() for l in _read(paths[0]).split('\n') if l.strip()]
    lines = _drop_commentary(lines)
    # Разбивка на главы; колонтитулы, номера страниц и мусорные строки выбрасываются
    chs = []
    for l in lines:
        s = l.strip()
        m = CHAP.match(s)
        if m:
            chs.append([m.group(1), None, []])
        elif PAGE_NUM.match(s) or RUN_HEAD.match(s) or s in GARBAGE:
            continue
        elif chs[-1][1] is None:
            chs[-1][1] = s  # строка названия главы
        else:
            chs[-1][2].append(l)
    assert [c[0] for c in chs] == ROMAN, f'ru_dem: заголовки {[c[0] for c in chs]}'
    assert [c[1] for c in chs] == TITLES, f'ru_dem: названия {[c[1] for c in chs]}'
    # Строки главы: мягкий перенос на конце — склейка без дефиса, иначе перевод строки
    res = []
    for _, _, body in chs:
        t = ''
        for l in body:
            t = t[:-1] + l if t.endswith('\xad') else (t + '\n' + l if t else l)
        assert '\xad' not in t, 'ru_dem: остался мягкий перенос'
        res.append(t)
    t = '\x00'.join(res)  # правки проверяются по всей книге сразу
    for bad, good, n in MARKERS:
        t = _sub(t, bad, good, n)
    t = _resub(t, MARK_HARE)
    for bad, good, n in HYPHEN:
        t = _sub(t, bad, good, n)
    t = t.replace('■', '')                    # мусорный знак распознавания перед тире
    t = re.sub(r'(^|\n)_ ', r'\1— ', t)       # «_» — распознанное тире в начале реплики
    if REPAIR_OCR:
        for bad, good, n in OCR:
            t = _sub(t, bad, good, n)
        t = _resub(t, OCR_HARE)
        t = _resub(t, OCR_Z)
    res = t.split('\x00')
    body = '\n'.join(res)
    # Контроль: не осталось меток, звёздочек, переносов на конце строки и посторонних цифр
    assert '*' not in body and '■' not in body, 'ru_dem: осталась звёздочка или мусор'
    assert not re.search(r'[^\W\d_]-\n', body), 'ru_dem: остался дефис на конце строки'
    digits = set(re.findall(r'\d+', body))  # «Правило 42», «42-е» — текст книги
    assert digits <= ({'42'} if REPAIR_OCR else {'42', '6'}), f'ru_dem: остались цифры {digits}'
    if REPAIR_OCR:
        latin = set(re.findall(r'[A-Za-zÀ-ÿ]+', body))
        assert latin == {'Où', 'est', 'ma', 'chatte'}, f'ru_dem: латиница {latin}'
        assert not re.search(r'[<>\\\[\]{}#]', body), 'ru_dem: остались знаки-мусор распознавания'
    # Сверка границ по содержанию: первая и последняя фразы книги (как в английском)
    assert res[0].startswith('Алисе наскучило сидеть с сестрой без дела на берегу реки')
    assert res[-1].endswith('вспомнит свое детство и счастливые\nлетние дни.')
    return res
