"""ru_zakh — S-21, Б. Заходер, «Алиса в Стране Чудес», пересказ (вне зачёта), файл ru_zakh_00.txt
(учебный файл Tviskaron/mipt 2019/python/04-sem/alice.txt). UTF-8, LF.
Абзац начинается пятью пробелами, продолжения абзаца — без отступа. Заголовок главы — строка
«ГЛАВА ПЕРВАЯ,», пустая строка, строка-подзаголовок с отступом («в которой Алиса чуть не
провалилась сквозь Землю»; в главе IV «0 которой…» — ошибка распознавания), пустые строки.
Глав 13: вставная «ГЛАВА НИКАКАЯ, из которой тем не менее можно кое-что узнать» и главы
ПЕРВАЯ…ДВЕНАДЦАТАЯ. По заданию «Глава никакая» возвращается первой главой, хотя сам Заходер в её
конце называет её «всего-навсего ПРЕДИСЛОВИЕ» (для счёта повествования её можно отбросить: res[1:]).
Глава XII у Заходера кончается сном Алисы («…никогда не забудешь...»): финального видения сестры
в пересказе нет — это свойство текста, а не обрыв файла.
Удаляется:
- титул («Льюис Кэрролл. АЛИСА В СТРАНЕ ЧУДЕС», «Пересказ с английского БОРИСА ЗАХОДЕРА»);
- заголовки и подзаголовки глав;
- сноски Заходера. В учебном файле они стоят в тексте отдельными абзацами: начинаются с «???»
  (21 шт., «??? Между прочим: ДОДО…»), с «//?» (1 шт., «Вильгельм Завоеватель высадился…»)
  или с отступа в шесть пробелов вместо пяти (2 шт.: «Мы-то с вами… антиподами.» и «Многие
  (особенно папы и мамы)… вот оно:» — последняя идёт вместе со стихами-оригиналом «Дети, в школу
  собирайтесь», строкой-меткой «//» и абзацем «Теперь, я надеюсь, всем понятно…», до
  «…которые она прочла.»);
- мусор учебного файла: звёздочки «* к ногам», «*чего» (2 шт.).
Переносы: остатки разрыва слов «подзе-» / «мелья», «Шля- па», «напосле- док», «стро- го»
склеиваются; «где- нибудь», «вот- вот», «Никому- то», «Швейцар-» / «Головастик» — настоящий
дефис, снимается только пробел/перевод строки. В хвосте мыши («хле-» / «ба», «по-» / «да-» / «м»)
слова тоже склеиваются. «докакого-нибудьберега-» (слипшиеся слова) разделяется; тире, слипшееся со
словами («Алиса-пожалуйста», «Конек-это»), отделяется пробелом.
Тире вида «старик- молвил» — пунктуация, не трогается. Прочие опечатки источника не правятся."""
import re

ORD = ['НИКАКАЯ', 'ПЕРВАЯ', 'ВТОРАЯ', 'ТРЕТЬЯ', 'ЧЕТВЕРТАЯ', 'ПЯТАЯ', 'ШЕСТАЯ', 'СЕДЬМАЯ',
       'ВОСЬМАЯ', 'ДЕВЯТАЯ', 'ДЕСЯТАЯ', 'ОДИННАДЦАТАЯ', 'ДВЕНАДЦАТАЯ']
# Подзаголовки — сверка заголовков по содержанию (как в файле, с его опечатками)
SUBTITLES = ['из которой тем не менее можно кое-что узнать',
             'в которой Алиса чуть не провалилась сквозь Землю',
             'в которой Алиса купается в слезах',
             'в которой происходит Кросс по Инстанциям и история с хвостиком',
             '0 которой Тритон Билль вылетает в трубу',
             'в которой Червяк дает полезные советы',
             'в которой встречаются поросенок и перец',
             'в которой пьют чай как ненормальные',
             'в которой играют в крокет у Королевы',
             'в которой рассказана история Деликатеса',
             'в которой танцуют Раковую Кадриль',
             'в которой выясняется, кто стащил пирожки',
             'в которой Алиса свидедельствует']
# «ГЛАВА <порядковое>,», пустая строка, подзаголовок с отступом
HEAD = re.compile(r'^ГЛАВА (%s),[ \t]*\n[ \t]*\n[ \t]+(.+)\n' % '|'.join(ORD), re.M)
TITLE_PAGE = ['Льюис Кэрролл. АЛИСА В СТРАНЕ ЧУДЕС', 'Пересказ с английского БОРИСА ЗАХОДЕРА']
# Начало абзаца-сноски: «???», «//?» после обычного отступа или отступ в шесть пробелов
NOTE_START = re.compile(r'^( {5}(\?\?\?|//\?)| {6}\S)')
# Сноска, которая тянется через несколько абзацев (стихи-оригинал и «//»): её последняя строка
NOTE_LONG = {'Многие (особенно папы и мамы)': 'которые она прочла.'}
N_NOTES = 24  # 21 «???» + 1 «//?» + 2 с отступом в шесть пробелов
# Остатки переноса и слипшиеся слова: (что, на что); каждая замена должна найтись ровно один раз
FIXES = [('подзе-\nмелья', 'подземелья'), ('Шля- па', 'Шляпа'), ('напосле- док', 'напоследок'),
         ('стро- го', 'строго'), ('где- нибудь', 'где-нибудь'), ('вот- вот', 'вот-вот'),
         ('Никому- то', 'Никому-то'), ('Швейцар-\nГоловастик', 'Швейцар-Головастик'),
         ('хле-\nба', 'хлеба'), ('по-\nда-\nм\n!', 'подам!'),
         ('докакого-нибудьберега- Вот', 'до какого-нибудь берега. Вот'),
         # Тире, слипшееся с соседними словами без пробелов (в файле тире — «-» с пробелом)
         ('Алиса-пожалуйста', 'Алиса- пожалуйста'), ("'Конек-это", "'Конек - это"),
         ('* к ногам', 'к ногам'), ('*чего', 'чего')]


def _read(path):
    with open(path, 'rb') as f:
        t = f.read().decode('utf-8-sig')
    return t.replace('\r\n', '\n').replace('\r', '\n')


def _drop_notes(body):
    """Убирает абзацы-сноски; возвращает (текст, число сносок)."""
    out, n, until, in_note = [], 0, None, False
    for line in body.split('\n'):
        if until is not None:  # длинная сноска: ждём её последнюю строку
            if until in line:
                until = None
            continue
        if NOTE_START.match(line):
            n += 1
            in_note = True
            until = next((e for s, e in NOTE_LONG.items() if s in line), None)
            continue
        if in_note and line.strip() and not line.startswith(' '):
            continue  # продолжение абзаца-сноски (строка без отступа)
        in_note = False
        out.append(line)
    assert until is None, 'ru_zakh: не найден конец длинной сноски'
    return '\n'.join(out), n


def _clean(body):
    """Тело главы: строки без отступов, строфы и абзацы-пробелы схлопнуты до одной пустой строки."""
    lines = [l.strip() for l in body.split('\n')]
    t = '\n'.join(lines)
    t = re.sub(r'\n{3,}', '\n\n', t)
    return t.strip('\n')


def chapters(paths):
    t = _read(paths[0])
    heads = list(HEAD.finditer(t))
    assert [h.group(1) for h in heads] == ORD, f'ru_zakh: заголовки {[h.group(1) for h in heads]}'
    assert [h.group(2).strip() for h in heads] == SUBTITLES, 'ru_zakh: подзаголовки не совпали'
    front = [l.strip() for l in t[:heads[0].start()].split('\n') if l.strip()]
    assert front == TITLE_PAGE, f'ru_zakh: перед «Главой никакой» неожиданный текст {front}'
    ends = [h.start() for h in heads[1:]] + [len(t)]
    res, notes = [], 0
    for h, e in zip(heads, ends):
        body, n = _drop_notes(t[h.end():e])
        notes += n
        res.append(_clean(body))
    assert notes == N_NOTES, f'ru_zakh: сносок {notes}, ожидалось {N_NOTES}'
    # Склейки переносов и мусор учебного файла — по тексту всех глав, каждая ровно один раз
    joined = '\x00'.join(res)
    for bad, good in FIXES:
        assert joined.count(bad) == 1, f'ru_zakh: «{bad}» встречается {joined.count(bad)} раз'
        joined = joined.replace(bad, good)
    res = joined.split('\x00')
    body = '\n'.join(res)
    for junk in ('???', '//', '*'):
        assert junk not in body, f'ru_zakh: осталось «{junk}»'
    # Сверка границ по содержанию: начало предисловия, первая фраза сказки, конец книги
    assert res[0].startswith('Больше всего на свете я ненавижу обман')
    assert res[0].endswith('начало книжки о приключениях Алиски в Расчудесии...')
    assert res[1].startswith('Алиса сидела со старшей сестрой на берегу и маялась')
    assert res[-1].endswith('сон, который, наверно, никогда не\nзабудешь...')
    # «Глава никакая» — предисловие (сам Заходер: «всего-навсего ПРЕДИСЛОВИЕ»); по PLAN предисловия удаляются
    return res[1:]
