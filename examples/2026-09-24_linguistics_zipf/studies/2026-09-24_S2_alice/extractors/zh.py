def _paragraphs(z, name, title):
    """Абзацы главы (текст между <br />) без заголовка; проверка, что других тегов нет."""
    s = z.read(name).decode('utf-8-sig')
    h3 = re.findall(r'<h3>(.*?)</h3>', s)
    assert len(h3) == 1 and h3[0].startswith(title), f'zh: {name}: заголовок {h3}'
    body = s.split('</h3>', 1)[1].split('</div>', 1)[0]
    parts = re.split(r'<br\s*/>', body)
    assert not any('<' in p or '>' in p for p in parts), f'zh: {name}: теги внутри главы'
    parts = [html.unescape(p).replace('\r', '').replace('\n', '').rstrip() for p in parts]
    return [p for p in parts if p.strip()]


def _restore(paras, k):
    """Возвращает в текст абзацы-«примечания», которые на деле — текст Кэрролла (RESTORE); отступ абзаца сохраняется."""
    for old, new in RESTORE.get(k, []):
        hits = [i for i, p in enumerate(paras) if p.lstrip('　 ') == old]
        assert len(hits) == 1, f'zh: гл. {k}: абзац «{old[:20]}…» найден {len(hits)} раз, ожидался 1'
        i = hits[0]
        paras[i] = paras[i][:len(paras[i]) - len(old)] + new
    return paras


def _drop_tail_and_notes(paras, k):
    """Обрезает редакторский хвост главы и снимает абзацы-примечания."""
    lead = [p.lstrip('　 ') for p in paras]
    cut = next((i for i, p in enumerate(lead) if p.startswith(TAIL)), len(paras))
    out, depth = [], 0
    for p, q in zip(paras[:cut], lead[:cut]):
        if depth == 0 and q.startswith(NOTE_START):
            if q.startswith('〔'):
                depth = q.count('〔') - q.count('〕')       # многоабзацное примечание — до парной «〕»
            else:
                assert q.endswith(('〉', '）')), f'zh: гл. {k}: незакрытое примечание {q[:30]}'
            continue
        if depth > 0:
            depth += p.count('〔') - p.count('〕')
            continue
        out.append(p)
    assert depth == 0, f'zh: гл. {k}: примечание не закрыто'
    return out


def chapters(paths):
    z = zipfile.ZipFile(paths[0])
    res = []
    for k, (name, title) in enumerate(zip(CHAPTER_FILES, TITLES), 1):
        t = '\n'.join(_drop_tail_and_notes(_restore(_paragraphs(z, name, title), k), k))
        for old, new, n in EDITS.get(k, []):
            assert t.count(old) == n, f'zh: гл. {k}: «{old}» встречается {t.count(old)} раз, ожидалось {n}'
            t = t.replace(old, new)
        t = MARKERS.sub('', t)
        t = GLOSS.sub('', t)
        # Проверки: разметки и примечаний не осталось; латиница и чжуинь — только текст Чжао
        for bad in ('〔', '〕', '〈', '〉', '（註', '註：', '※', '●', '★', '◆', '【'):
            assert bad not in t, f'zh: гл. {k}: осталось {bad!r}'
        latin = re.findall(r'[A-Za-zＡ-Ｚａ-ｚ]+', t)
        assert latin == LATIN.get(k, []), f'zh: гл. {k}: латиница {latin}'
        bopo = BOPO.findall(t)
        assert bopo == BOPOMOFO.get(k, []), f'zh: гл. {k}: чжуинь {bopo}'
        if ENDS[k - 1]:
            assert t.endswith(ENDS[k - 1]), f'zh: гл. {k}: конец {t[-40:]!r}'
        else:
            assert SOUP_END.search(t), f'zh: гл. {k}: конец {t[-40:]!r}'
        res.append(t)
    # Ремарка Кэрролла о Грифоне стоит сразу после того, как Грифона нашли спящим на солнце
    assert '牠在太陽裏熟睡著。\n　　（你要是不知道骨敕鳳是什麼，看第廿一畫便知）\n' in res[8], 'zh: гл. IX: ремарка о Грифоне'
    # Сверка начала книги: «Alice was beginning to get very tired of sitting by her sister on the bank…»
    assert res[0].startswith('　　阿麗思陪著她姊姊閒坐在河邊上沒有事做，坐得好不耐煩。'), 'zh: начало главы I'
    return res
