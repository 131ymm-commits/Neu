# -*- coding: utf-8 -*-
"""DISTILL-02: ожидания до прогона (PREREG §6) — из prereg_power_d2.json (пилот 3, совет 74). Вероятность = 0,95 × решающая мощность при
τ пилота (как в OCDIV-03/04); при τ из верхней границы — рядом, описательно. Р2-Л (описательное по решению совета) — ожидание «среднее m2
по средам < 0,5» с 0,95 × P из той же модели. Пишет expect_d2.json и печатает строки для tools/self_calibration.py.
Ожидания E1–E9 условны на перенос свойств сред OCDIV-04 (μ, τ, s пилота) на свежие задачи и новые среды (совет 74, п. 6).
  python3 prereg_expect_d2.py"""
import json
import os

X = os.path.dirname(os.path.abspath(__file__))
PWJ = json.load(open(os.path.join(X, 'prereg_power_d2.json'), encoding='utf-8'))
PW, ACT = PWJ['rules'], PWJ['active']
TEXT = {'Р1-Т': 'Р1-Т подтверждено: программа лучше частот смещений (B1) по лог-вероятности ответа, «тысячи», 8 сред (А и Б)',
        'Р1-Л': 'Р1-Л подтверждено: то же на «длине», 3 среды (часть А)',
        'Р1Ф-Т': 'Р1Ф-Т подтверждено: программа лучше Φ-базы (Wen и др.), «тысячи» (А и Б)',
        'Р1Ф-Л': 'Р1Ф-Л подтверждено: программа лучше Φ-базы, «длина» (часть А)',
        'Р2-Т': 'Р2-Т подтверждено: программа берёт больше половины объяснимого против одного ящика, «тысячи» (А и Б)',
        'Р3-Л': 'Р3-Л решающий вердикт в любую сторону: совпадение ошибок голов ≠ программам, «длина» (часть А)',
        'Р4-Т': 'Р4-Т подтверждено: на новых средах (пятизначные a) программа знает места переноса лучше частот B1 (часть А; по заменителю)',
        'Р4Ф-Т': 'Р4Ф-Т подтверждено: на новых средах (пятизначные a) программа лучше Φ-базы (часть А; по заменителю X 19–49 → 59–89)'}


def c(x, d):
    return f'{x:.{d}f}'.replace('.', ',')


E = []
for r in [r for r in PW if ACT[r]]:
    e = PW[r]
    E.append(dict(id=f'E{len(E) + 1}', rule=r, key=(f'{r}:решающий' if r.startswith('Р3') else f'{r}:подтверждено'), p=round(0.95 * e['decisive'], 6),
                  trivial=False, text=TEXT[r], basis=f"0,95 × решающая мощность {c(e['decisive'], 6)} при τ = {c(e['tau'], 4)} (при τ из верхней "
                                                     f"границы {c(e['tau_hi'], 4)} — {c(e['decisive_tau_hi'], 6)}); набор пилота 3 {e['source']}"))
p2 = PWJ['r2l_calibration']
E.append(dict(id=f'E{len(E) + 1}', rule='Р2-Л', key='Р2-Л:m2<0,5', p=round(0.95 * p2['p_below'], 6), trivial=False,
              text='Р2-Л (описательное): среднее m2 (от одного ящика) по трём средам «длины» test5 меньше 0,5',
              basis=f"0,95 × P(среднее < 0,5) = {c(p2['p_below'], 6)} в модели «новая среда» (при τ из верхней границы — {c(p2['p_below_tau_hi'], 6)}); "
                    f"среднее m2 пилота 3 — {c(p2['mu_m2'], 4)}; направление записано советом 74 (формалист)"))
E.append(dict(id=f'E{len(E) + 1}', rule=None, key='method', p=0.95, trivial=True, text='опыт определён: в каждом семействе годны все среды теста',
              basis='тривиальное: в пилоте у всех сред 7 голов'))
json.dump(dict(source='prereg_power_d2.json (пилот 3, gha_out/distill02_pilot3/pilot3.json)', rule='вероятность = 0,95 × решающая мощность при τ пилота',
               conditional='ожидания условны на перенос свойств сред OCDIV-04 (μ, τ, s) на свежие задачи и новые среды (совет 74, п. 6)',
               expectations=E), open(os.path.join(X, 'expect_d2.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
for e in E:
    note = ('(после пилота) тривиальное — вне сводной калибровки; ' if e['trivial'] else '') + e['basis'] + '; expect_d2.json; ждёт результата'
    print(repr(('DISTILL-02', f"{e['id']} {e['text']}", 'PREREG-DISTILL-02 §6', 'вероятность', round(e['p'], 4), None, note)) + ',')
