def logu(r, lo, hi): return int(math.exp(r.uniform(math.log(lo), math.log(hi))))
def odd_nonround(r, lo, hi):  # некруглое число: не кратно 10 и не степень
    while True:
        x = logu(r, lo, hi)
        if x % 10 and x % 1000 != 1 and not str(x).rstrip('0').endswith('000'): return x

