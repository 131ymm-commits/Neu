def neck(kind, noadj, counts, one_adj=False):
    def f(r, lv):
        n = r.randint(14, 26) if lv == 'base' else r.randint(28, 40); k = 3 if counts else r.randint(3, 5)
        p = dict(n=n, k=k, group=kind, noadj=noadj, one_adj=one_adj)
        if counts == 'all':
            while True:
                a = r.randint(2, n // 2); b = r.randint(2, n - a - 2); c = n - a - b
                if c >= 2: break
            p['counts'] = {'1': a, '2': b, '3': c}
        elif counts == 'one': p['counts'] = {'1': r.randint(3, n // 3)}
        g = 'ожерелий (одинаковыми считаются раскраски, переходящие друг в друга при повороте круга)' if kind == 'C' else 'браслетов (одинаковыми считаются раскраски, переходящие друг в друга при повороте или при отражении круга)'
        conds = []
        if noadj: conds.append('никакие две соседние бусины не одного цвета')
        if one_adj: conds.append('никакие две соседние бусины не обе цвета 1')
        if counts == 'all': conds.append(f"бусин цвета 1 ровно {p['counts']['1']}, цвета 2 — ровно {p['counts']['2']}, цвета 3 — ровно {p['counts']['3']}")
        if counts == 'one': conds.append(f"бусин цвета 1 ровно {p['counts']['1']} (остальные цвета — в любом количестве, в том числе 0)")
        t = (f"На круге {n} бусин (бусины 1 и {n} тоже соседние). Каждую красят в один из {k} цветов (1, …, {k}); не обязательно использовать все цвета. "
             f"Сколько существует различных {g}, у которых " + '; '.join(conds) + '?')
        return p, t
    return f
