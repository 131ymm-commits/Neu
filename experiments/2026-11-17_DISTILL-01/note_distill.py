#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""DISTILL-01: записка разведки из gha_out/distill01_explore/distill.json. Числа — из json тем же форматированием, что сверяет
ledger.py audit; производные (доли видов ошибки, отношения) — в note_derived.json. Описательно, пост-хок, вердиктов нет.
  python3 note_distill.py [DISTILL.json OUT.md]"""
import json
import os
import sys

X = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(X))
a = sys.argv[1:]
d = json.load(open(os.path.join(ROOT, a[0] if a else 'gha_out/distill01_explore/distill.json'), encoding='utf-8'))
OUT = a[1] if len(a) > 1 else os.path.join(X, 'NOTE-DISTILL-01.md')


def n(x, k=3, sign=False):
    if x is None:
        return '—'
    s = f'{abs(x):.{k}f}'.replace('.', ',')
    if x < 0 and float(s.replace(',', '.')) != 0:
        return '−' + s
    return ('+' if sign and x > 0 and float(s.replace(',', '.')) != 0 else '') + s


F = d['formulas']
H2, H1 = d['hold']['test_ocdiv2'], d['hold']['test_ocdiv1']
heads = list(F)
der = dict(kinds={}, auc_diff_ocdiv2={}, auc_diff_ocdiv1={}, t4_ratio={})
for h, tab in d['kinds_fit'].items():
    tot, nn = {}, 0
    for v in tab.values():
        nn += v['n']
        for kk, s in v['share'].items():
            tot[kk] = tot.get(kk, 0) + s * v['n']
    der['kinds'][h] = dict(n=nn, share={kk: tot[kk] / nn for kk in tot})
for h in heads:
    e2, e1 = H2['eval'][h], H1['eval'][h]
    der['auc_diff_ocdiv2'][h] = e2['auc_formula_numeric'] - e2['auc_confidence_numeric']
    der['auc_diff_ocdiv1'][h] = e1['auc_formula_numeric'] - e1['auc_confidence_numeric']
for env, t in (H2['t4'] or {}).items():
    der['t4_ratio'][env] = (t['T4_observed'] / t['T4_pred']) if t['T4_pred'] and abs(t['T4_pred']) > 1e-4 else None
der['top_carry_in_all'] = all('top_carry' in F[h]['feats'] and F[h]['coef_rounded'][1 + F[h]['feats'].index('top_carry')] > 0 for h in heads)
der['top_carry_coef'] = {h: F[h]['coef_rounded'][1 + F[h]['feats'].index('top_carry')] for h in heads if 'top_carry' in F[h]['feats']}
der['formula_ge_conf_ocdiv2'] = int(sum(v >= 0 for v in der['auc_diff_ocdiv2'].values()))
der['formula_lt_conf_ocdiv1'] = int(sum(v < 0 for v in der['auc_diff_ocdiv1'].values()))
json.dump(der, open(os.path.join(X, 'note_derived.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
tc = der['top_carry_coef']

L = []
add = L.append
add('# DISTILL-01 «ДИСТИЛЛЯЦИЯ-ГОЛОВ» — записка разведки (17.11.2026)')
add('')
add('Слова автора: «Упрощаем — дистилируем ИИ. Да давай додистилируемся до осознаваемой математики». План с мерилом «осознаваемости» '
    'закоммичен до кода (1d1fcc62); код и тесты — cca58db3; разведка — задание `distill01_explore` на GitHub Actions '
    '(`gha_out/distill01_explore/distill.json`). **Всё ниже — описательно; на отложенных данных — пост-хок; вердиктов и записей в реестр нет.**')
add('')
add('## 1. Формулы ошибки семи голов (построены на пилоте 2 OCDIV-02: ' + f"{d['n_fit']} ответов, подсказка только из ID)")
add('')
add('| Голова | Формула | Доля ошибок на построении |')
add('|---|---|---|')
for h in heads:
    add(f"| {h} | `{F[h]['formula']}` | {n(F[h]['err_rate'], 4)} |")
add('')
add('Признаки: `top_carry` — разряд старшего переноса (0 — единицы; −1 — переносов нет); `nd_a` — цифр в a; `nines` — девяток в a; '
    '`ood` — сумма вне диапазона калибровки; `new_place` — сумма длиннее a; `carries` — число переносов. Коэффициенты округлены до двух '
    'значащих цифр, и все меры ниже посчитаны по округлённым формулам.')
add('')
add(f"- **Общий закон:** у всех {len(heads)} голов в формуле есть разряд старшего переноса, и всегда со знаком «+» "
    f"(коэффициент от {n(min(tc.values()), 2)} до {n(max(tc.values()), 2)}): чем старше разряд, куда идёт перенос, тем вероятнее ошибка.")
add('- Остальные члены у голов разные. Их знаки — условные: признаки связаны между собой (длина, девятки, выход за диапазон), поэтому '
    '«минус» у `ood` или `nines` при уже учтённых `top_carry` и `nd_a` не значит, что выход за диапазон помогает. Объяснение не проверялось.')
add('')
add('## 2. Насколько формулы верны (AUC предсказания ошибки на задачах с числовым ответом)')
add('')
add('| Голова | OCDIV-02 тест («длина», та же подсказка): формула | уверенность головы | OCDIV-01 тест (другая подсказка, трёхзначные): формула | уверенность головы |')
add('|---|---|---|---|---|')
for h in heads:
    e2, e1 = H2['eval'][h], H1['eval'][h]
    add(f"| {h} | {n(e2['auc_formula_numeric'])} | {n(e2['auc_confidence_numeric'])} | {n(e1['auc_formula_numeric'])} | {n(e1['auc_confidence_numeric'])} |")
add('')
add(f"- **На той же подсказке** формула из трёх признаков входа предсказывает ошибки головы не хуже её собственной уверенности: "
    f"формула ≥ уверенности у {der['formula_ge_conf_ocdiv2']} голов из {len(heads)}.")
add(f"- **На другой подсказке** (OCDIV-01) формулы не переносятся — AUC около 0,5, а уверенность головы остаётся хорошей: "
    f"формула < уверенности у {der['formula_lt_conf_ocdiv1']} голов из {len(heads)}. Закон ошибок зависит от режима (подсказки и длины), а не "
    'только от головы.')
add('- Лог-потери и «доля объяснимого» здесь не читаются: доля ошибок на построении и на отложенных данных разная, и сдвиг базовой '
    'частоты перекрывает различение (поле `share_explained` в json — описательно, с этой оговоркой).')
add('')
add('## 3. Как головы ошибаются (виды ошибки на построении, доля среди неверных числовых ответов)')
add('')
add('| Голова | неверных | потеря переноса (−10^k) | потеря разряда | лишний перенос (+10^k) | прочее |')
add('|---|---|---|---|---|---|')
for h in heads:
    k = der['kinds'][h]
    s = k['share']
    add(f"| {h} | {k['n']} | {n(s.get('потеря переноса', 0))} | {n(s.get('потеря разряда', 0))} | {n(s.get('лишний перенос', 0))} | {n(s.get('прочее', 0))} |")
add('')
add('- Потеря переноса даёт **однозначный** неверный ответ: правда − 10^k. Две головы, потерявшие один и тот же перенос, называют одно и то же '
    'неверное число. Это механизм-кандидат «совпадающих ошибок» (гомоплазии); объяснение не проверялось.')
add('')
add('## 4. Совпадение ошибок голов: что объясняет трудность по входу')
add('')
add('| Среда (тест OCDIV-02) | φ ошибок пар, факт | φ из формул (условная независимость) | доля | Т4 из формул | Т4 наблюдённый |')
add('|---|---|---|---|---|---|')
for env in sorted(H2['phi'], key=len):
    p, t = H2['phi'][env], (H2['t4'] or {}).get(env, {})
    add(f"| {env} | {n(p['phi_actual'])} | {n(p['phi_from_formulas'])} | {n(p['share'], 2)} | {n(t.get('T4_pred'), 4, True)} | {n(t.get('T4_observed'), 4, True)} |")
add('')
add('- **Корреляцию ошибок** пар трудность по входу в этом режиме в основном воспроизводит: доля от '
    f"{n(min(v['share'] for v in H2['phi'].values()), 2)} до {n(max(v['share'] for v in H2['phi'].values()), 2)}. На другой подсказке "
    f"(OCDIV-01) — лишь от {n(min(v['share'] for v in H1['phi'].values()), 2)} до {n(max(v['share'] for v in H1['phi'].values()), 2)}.")
t9 = H2['t4']['L_X9_p3']
add(f"- **Ложное большинство (Т4) трудность по входу не воспроизводит:** формулы при условной независимости и без совпадения неверных "
    f"ответов дают в L_X9_p3 {n(t9['T4_pred'], 4, True)}, а наблюдалось {n(t9['T4_observed'], 4, True)}. F₀ формулы почти совпадает с "
    f"наблюдённым ({n(t9['F0_pred'], 3)} против {n(t9['F0_observed'], 3)}), а F — нет ({n(t9['F_pred'], 3)} против {n(t9['F_observed'], 3)}). "
    'Избыток ложного большинства идёт не от различий трудности, видимых во входе. Кандидаты: совпадение самих неверных ответов (потеря одного '
    'и того же переноса, §3) и трудность, которой признаки не видят. Не проверялось.')
add('- Это расходится с прочтением совета 69 «Т4 может целиком давать трудность» — по крайней мере для трудности, видимой во входе. '
    'Пост-хок, на уже разобранных данных; вывод — только после проверки на свежих данных.')
add('')
add('## 5. Что это даёт')
add('- **Осознаваемая математика головы есть, но она местная.** В режиме «подсказка из ID, длинные числа» ошибку любой из семи голов предсказывает '
    'одна строка: σ(коэффициент · разряд старшего переноса + …). В другом режиме та же строка не работает.')
add('- **Для главного вопроса (оценщик):** оценщик по признакам входа силён внутри режима, где его вывели, и слеп вне его; собственная уверенность '
    'головы слабее внутри сдвига, но переносится между режимами. Кандидат — оценщик, который совмещает оба (предложение).')
add('- **Для OCDIV-03 (предрегистрация на тесте «тысяч», он не тронут):**')
add('  - нуль Т4 со стратами по `top_carry` и `nd_a` — признакам, которые дистилляция нашла у всех голов;')
add('  - заранее записанное предсказание формул: Т4 из формул (условная независимость) близок к нулю, а наблюдённый Т4 его превысит, если '
    'совпадение неверных ответов настоящее;')
add('  - вторая ступень формулы: добавить совпадение неверных ответов через виды ошибки (потеря одного переноса) и предсказать Т4 до прогона.')
add('- **Следующая ступень дистилляции:** механизм внутри одной головы (где в ней «теряется» перенос) — после этого.')
add('')
add('## 6. Оговорки')
add('- Данные построения и отложенные данные OCDIV-02 — один режим подсказки; места задач и p разные, но семейство «длина» входит в обе части.')
add('- Формулы выбраны жадно по BIC; другая процедура могла выбрать другие вторые и третьи члены. Общий член `top_carry` — устойчивость не проверялась.')
add('- Т4 из формул считается при упрощении «неверные ответы не совпадают»; это нижняя оценка того, что даёт одна трудность.')
add('- Сравнение с уверенностью — на задачах с числовым ответом; формулы оценивались по округлённым коэффициентам.')
open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('записано', OUT)
