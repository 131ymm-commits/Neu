# Порог = наименьшее k с P(X ≥ k | n, ½) ≤ alpha/2 — та же функция thresh, что в evo06_analyze.py: alpha — двусторонний уровень теста,
# на хвост приходится alpha/2. Первичные: две гипотезы при alpha = 0,025 каждая (хвост 0,0125; Бонферрони = первый шаг Холма на двух,
# второй шаг не делается). Вторичные — Холм по двусторонним p. Пример: n=120, alpha=0,025 → 73 (P(≥73|½)=0,0110, 2·P=0,022 ≤ 0,025; у 72 2·P=0,035).
# Мощность — P(X ≥ k | n, p) при доле побед p = 0,60…0,75. Все числа — полный перебор scipy.stats.binom, не Монте-Карло.
import numpy as np
from scipy.stats import binom

PS = (0.60, 0.65, 0.70, 0.75)


def thresh(n, alpha):
    ks = [k for k in range(n + 1) if binom.sf(k - 1, n, .5) <= alpha / 2]
    return ks[0] if ks else None


def row(n, alpha, label):
    k = thresh(n, alpha); p1 = binom.sf(k - 1, n, .5)
    pw = ' '.join(f'мощн.(p={p})={binom.sf(k - 1, n, p):.2f}' for p in PS)
    print(f'  {label}: порог {k}/{n}, P(≥{k}|½)={p1:.4f} (двусторонне {2 * p1:.4f}); {pw}')
    return k, p1


print('Пороги и мощность знакового теста (полный перебор binom). n — число пар без ничьих (n_eff).')
print('Первичные H2/H3: двусторонний alpha=0,025 на тест (Бонферрони на две = Холм на двух без второго шага). Вторичные: Холм по p двусторонним.')
for n in (120, 110, 100, 90, 80, 60, 45, 40):
    print(f'== n = {n} пар')
    k, p1 = row(n, 0.025, 'первичные, двусторонний α/2 = 0,025 на тест')
    row(n, 0.05, 'одиночный тест, двусторонний α = 0,05')
    lo, hi = int(binom.ppf(0.025, n, .5)), int(binom.ppf(0.975, n, .5))
    print(f'  A/A: 95 % интервал числа побед при p=½: [{lo}, {hi}]')
    print(f'  ложный уровень на тест при пороге {k}/{n}: 2·P(≥{k}) = {2 * p1:.4f}; на серию из двух первичных (сумма, FWER ≤) {4 * p1:.4f};'
          f' точно 1−(1−{2 * p1:.4f})² = {1 - (1 - 2 * p1) ** 2:.4f}')
print('== критерий «вдвое», незнание базы (T2–T5): один тест, двусторонний α = 0,05')
for n in (80, 70, 60, 40):
    row(n, 0.05, f'n={n}')
