# SCORE-01: тексты промпта оценщика и правил оплаты. Замораживаются по SHA-256 до микропилота; менять после пилота —
# только с записью в PREREG (что и почему). Роль — промпт C SELECT-01 (experiments/2026-10-07_SELECT-01/prompts.py, ROLE),
# ответ — вероятности вместо номера; руки отличаются одной фразой правила оплаты.
#   python3 prompts_score.py hash   — напечатать хеши
import hashlib
import json
import sys

ROLE_P = """Ты — независимый оценщик планов. Автор планов тебе неизвестен, его мнения у тебя нет — и не нужно: оценивай только по правилам задачи.
Порядок работы:
1) для каждого кандидата проследи по правилам ход событий по шагам на прогнозных (средних) значениях и найди, где план теряет: штрафы, списания, урезанные заказы, простои, переналадки, износ, опоздания;
2) учти случайность: какой план устойчивее, если факт отклонится от прогноза;
3) сравни кандидатов по ожидаемому итогу, а не по тому, насколько план выглядит продуманным.
Считай в уме; инструментов нет, код не запускай, файлы не открывай.
Верни p — список из {k} чисел: p[i] — твоя вероятность того, что кандидат i фактически лучший, то есть что у него наибольший ожидаемый итог (среднее по случайности). Числа неотрицательные, сумма — 1.
{rule}

{rules}

{cands}"""

RULES_PAY = dict(
    LOG='Как тебя оценят: счёт = натуральный логарифм вероятности, которую ты дал фактически лучшему кандидату (ln p). '
        'Чем больше, тем лучше; вероятность 0 у фактически лучшего — худший возможный счёт.',
    WIN='Как тебя оценят: счёт = 1, если кандидат, которому ты дал наибольшую вероятность, фактически лучший; иначе 0.',
)

SCHEMA = {"type": "object", "properties": {"p": {"type": "array", "minItems": 8, "maxItems": 8,
                                                  "items": {"type": "number", "minimum": 0}}}, "required": ["p"]}


# --- формат «в лучшей половине» (после микропилота 0: формат «лучший из 8» не оставил оценщику навыка; PILOT0.md) ---
ROLE_H = ROLE_P.split('Верни p — список')[0] + """Ровно четыре из {k} кандидатов — в лучшей половине: их ожидаемый итог (среднее по случайности) выше, чем у остальных четырёх.
Верни p — список из {k} чисел от 0 до 1: p[i] — твоя вероятность того, что кандидат i в лучшей половине.
{rule}

{rules}

{cands}"""

RULES_HALF = dict(
    LOG='Как тебя оценят: по каждому кандидату — натуральный логарифм вероятности, которую ты дал верному ответу '
        '(p[i], если кандидат в лучшей половине, и 1 − p[i], если нет); счёт — сумма по восьми кандидатам. '
        'Чем больше, тем лучше; вероятность 0 у верного ответа — худший возможный счёт.',
    WIN='Как тебя оценят: по каждому кандидату — 1 очко, если твой ответ верен (p[i] > 0,5 у кандидата из лучшей половины '
        'или p[i] < 0,5 у кандидата из худшей), 0 — если неверен, ½ — при p[i] = 0,5; счёт — сумма по восьми кандидатам.',
)

SCHEMA_H = {"type": "object", "properties": {"p": {"type": "array", "minItems": 8, "maxItems": 8,
                                                    "items": {"type": "number", "minimum": 0, "maximum": 1}}}, "required": ["p"]}


def prompt_half(arm, rules, shown):
    return ROLE_H.format(k=len(shown), rule=RULES_HALF[arm], rules=rules, cands=cands_text(shown))


def cands_text(pool):
    return '\n'.join(f'Кандидат {i}: план {json.dumps(c["plan"], ensure_ascii=False)}' for i, c in enumerate(pool))


def prompt(arm, rules, shown):
    return ROLE_P.format(k=len(shown), rule=RULES_PAY[arm], rules=rules, cands=cands_text(shown))


def hashes():
    h = lambda s: hashlib.sha256(s.encode()).hexdigest()
    return dict(ROLE_P=h(ROLE_P), LOG=h(RULES_PAY['LOG']), WIN=h(RULES_PAY['WIN']), schema=h(json.dumps(SCHEMA, sort_keys=True)),
                ROLE_H=h(ROLE_H), LOG_H=h(RULES_HALF['LOG']), WIN_H=h(RULES_HALF['WIN']), schema_H=h(json.dumps(SCHEMA_H, sort_keys=True)))


if __name__ == '__main__' and sys.argv[1:2] == ['hash']:
    print(json.dumps(hashes(), indent=1))
