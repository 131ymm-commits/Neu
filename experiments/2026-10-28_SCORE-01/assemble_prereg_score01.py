def main():
    status = sys.argv[sys.argv.index('--status') + 1] if '--status' in sys.argv else 'черновик; не регистрация'
    out_name = sys.argv[sys.argv.index('--out') + 1] if '--out' in sys.argv else 'DRAFT-PREREG-SCORE-01.md'
    T1 = run('pilot_tables.py', 'pilot1_opus', 'pilot1_haiku')
    T2 = run('pilot2_tables.py', 'opus', 'haiku')
    T3 = run('pilot3_tables.py', 'opus', 'haiku')
    POW = json.load(open(os.path.join(HERE, 'pilot_power.json')))
    POW12 = json.load(open(os.path.join(HERE, 'pilot12_power.json')))
    POW12S = json.load(open(os.path.join(HERE, 'pilot12_power_single.json')))
    H = json.loads(run('prompts_score.py', 'hash'))
    CHK = {s: json.load(open(os.path.join(HERE, 'truth', f'check_{s}.json')))['summary'] for s in ('pilot', 'main', 'rep')}
    CTX = open(os.path.join(HERE, 'run', 'pilot_ctxcheck.log'), encoding='utf-8').read()
    CALLS = {k: journal_calls(k) for k in ('pilot0', 'pilot1', 'pilot2', 'pilot_ctxcheck', 'pilot3')}
    DIR_LINES, DIR_KEEP = L.direction_check()
    WL = L.win_log_out_pilots()
    SPLIT = L.rule_out_split()
    C, CTXL = ctx_lines()
    AA_TXT = '; '.join(f'{"Opus" if m == "opus" else "Haiku"} {arm} — {r}' for m, arm, r in corr_aa(T3))
    SD_TXT = '; '.join(f"{'Opus' if m == 'opus' else 'Haiku'}: (LOG − NONE) {f(v['log_minus_none'], 0)} и (WIN − LOG)/2 {f(v['half_win_minus_log'], 0)}"
                       for m, v in SPLIT.items())
    tpl = open(os.path.join(HERE, 'prereg_template.md'), encoding='utf-8').read()
    out = (tpl.replace('{{STATUS}}', status).replace('{{PILOTS}}', pilots_block(T1, T2, T3, CTX, DIR_LINES, CALLS, H, CHK, WL, C, CTXL))
           .replace('{{PREDICTIONS}}', pred_lines()).replace('{{EXPECT}}', expect_lines()).replace('{{POWER}}', power_lines(POW, POW12, POW12S))
           .replace('{{RESOURCES}}', resources()).replace('{{AA_CORR}}', AA_TXT).replace('{{SD_SPLIT}}', SD_TXT))
    assert '{{' not in out, 'не все метки заменены'
    open(os.path.join(HERE, out_name), 'w', encoding='utf-8').write(out)
    print('собрано:', out_name, len(out), 'знаков; направления:', {k: (v['sign'], v['keep']) for k, v in DIR_KEEP.items()})


if __name__ == '__main__':
    main()
