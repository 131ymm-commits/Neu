# SELECT-01: тексты промптов голов. Замораживаются по SHA-256 до пилота (требование Скептика, совет 26, вариант (а)+(б));
# менять тексты, роли или модель рук после пилота — самообман (записано в DESIGN.md).
#   python3 prompts.py hash   — напечатать хеши
import hashlib, json, sys

# --- исполнитель: пул из k = 8 кандидатов, к каждому заявка и сомнения ---
EXEC = """Ниже — задача планирования. Предложи 8 РАЗНЫХ планов (разные стратегии, а не мелкие правки одного плана).
Для каждого плана дай:
- plan — план в указанном в задаче JSON-формате;
- claim — твой прогноз итога задачи для этого плана (одно число: ожидаемое значение итога с учётом случайности);
- doubt — твоя вероятность (0…1), что этот план окажется хуже среднего из восьми по фактическому итогу;
- note — одна фраза: идея плана и в чём главный риск.
Считай в уме; инструментов нет, код не запускай, файлы не открывай.

{rules}"""

# --- общий вид кандидатов для оценщиков ---
def cands_text(pool, with_claim):
    out = []
    for i, c in enumerate(pool):
        s = f'Кандидат {i}: план {json.dumps(c["plan"], ensure_ascii=False)}'
        if with_claim: s += f'\n  заявка автора о его итоге: {c["claim"]}; автор: «{c["note"]}»'
        out.append(s)
    return '\n'.join(out)

# B_слепой / B_заявка / A — базовый промпт «выбери лучший план»
BASE = """Ниже — задача планирования и {k} планов-кандидатов. Выбери план с наибольшим фактическим итогом.
Считай в уме; инструментов нет, код не запускай, файлы не открывай.
Верни choice — номер кандидата.

{rules}

{cands}"""

# C — ролевой промпт оценщика по правилам (тот же вход, что у B_слепой)
ROLE = """Ты — независимый оценщик планов. Автор планов тебе неизвестен, его мнения у тебя нет — и не нужно: оценивай только по правилам задачи.
Порядок работы:
1) для каждого кандидата проследи по правилам ход событий по шагам на прогнозных (средних) значениях и найди, где план теряет: штрафы, списания, урезанные заказы, простои, переналадки, износ, опоздания;
2) учти случайность: какой план устойчивее, если факт отклонится от прогноза;
3) сравни кандидатов по ожидаемому итогу, а не по тому, насколько план выглядит продуманным.
Считай в уме; инструментов нет, код не запускай, файлы не открывай.
Верни choice — номер кандидата с наибольшим ожидаемым итогом.

{rules}

{cands}"""

# D — тот же ролевой промпт с правом отказа
ROLE_REFUSE = ROLE.replace('Верни choice — номер кандидата с наибольшим ожидаемым итогом.',
    'Если ты не можешь отличить лучшего кандидата от остальных с разумной уверенностью — откажись: верни choice = -1 («не знаю»). Отказ не наказывается сам по себе.\nИначе верни choice — номер кандидата с наибольшим ожидаемым итогом.')

ARMS = dict(
    A=dict(tpl=BASE, claim=True),          # одна голова, видит план и заявку
    B_zayavka=dict(tpl=BASE, claim=True),  # N вызовов A, большинство
    B_blind=dict(tpl=BASE, claim=False),   # N вызовов базового промпта без заявки, большинство — главный контроль
    C=dict(tpl=ROLE, claim=False),         # один вызов ролевого оценщика (вторично)
    D=dict(tpl=ROLE_REFUSE, claim=False),  # один вызов ролевого оценщика с отказом (вторично)
    C_N=dict(tpl=ROLE, claim=False),       # N вызовов C, большинство — первичное семейство
    D_N=dict(tpl=ROLE_REFUSE, claim=False) # N вызовов D, большинство среди неотказавшихся — первичное семейство
)

def eval_prompt(arm, rules, pool):
    a = ARMS[arm]; return a['tpl'].format(k=len(pool), rules=rules, cands=cands_text(pool, a['claim']))

EXEC_SCHEMA = {"type": "object", "properties": {"candidates": {"type": "array", "minItems": 8, "maxItems": 8, "items": {
    "type": "object", "properties": {"plan": {"type": "object"}, "claim": {"type": "number"}, "doubt": {"type": "number"}, "note": {"type": "string"}},
    "required": ["plan", "claim", "doubt", "note"]}}}, "required": ["candidates"]}
EVAL_SCHEMA = {"type": "object", "properties": {"choice": {"type": "integer"}}, "required": ["choice"]}

def hashes():
    h = lambda s: hashlib.sha256(s.encode()).hexdigest()
    return dict(EXEC=h(EXEC), BASE=h(BASE), ROLE=h(ROLE), ROLE_REFUSE=h(ROLE_REFUSE),
                schemas=h(json.dumps([EXEC_SCHEMA, EVAL_SCHEMA], sort_keys=True)))

if __name__ == '__main__' and sys.argv[1:2] == ['hash']:
    print(json.dumps(hashes(), indent=1))
