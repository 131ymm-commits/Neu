def load_heroes() -> dict:
    with open(DATA / "heroes.json", encoding="utf-8") as f:
        return json.load(f)


def load_item_ids() -> set[str]:
    ids = set()
    with open(DATA / "items_internal.txt", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                ids.add(line)
    return ids
