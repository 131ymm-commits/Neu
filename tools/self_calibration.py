def expand():
    for r in ROWS:
        for _ in range(5 if r[0] == 'S2' else 1):
            yield r


def main():
    done = [r for r in expand() if r[5] is not None]
    brier = sum((p - t) ** 2 for *_, p, t, _ in done) / len(done)
    conf = sum(p for *_, p, t, _ in done) / len(done); hit = sum(t for *_, p, t, _ in done) / len(done)
    bins = {}
    for *_, p, t, _ in done:
        b = 'уверенно (≥ 0,75)' if p >= 0.75 else ('середина (0,5–0,7)' if p >= 0.5 else 'скорее нет (≤ 0,3)')
        bins.setdefault(b, []).append((p, t))
    lines = ['# Калибровка Claude как оценщика своих ожиданий',
             '', 'Генерирует `tools/self_calibration.py`. Ожидания взяты только из записанного ДО результата. Шкала слов → вероятность задана в коде один раз.', '',
             f'**Предсказаний с исходом: {len(done)}. Балл Брайера {brier:.3f}** (монетка 0,25; меньше — лучше). '
             f'Средняя уверенность {conf:.2f}, доля подтверждённых {hit:.2f}, **самообман {conf - hit:+.2f}**.', '',
             '| Уверенность | Число | Средняя уверенность | Доля подтверждённых |', '|---|---|---|---|']
    for b, v in bins.items():
        lines.append(f'| {b} | {len(v)} | {sum(p for p, _ in v) / len(v):.2f} | {sum(t for _, t in v) / len(v):.2f} |')
    lines += ['', '| Эксперимент | Предсказание | Ожидание | p | Исход | Заметка |', '|---|---|---|---|---|---|']
    for e, what, where, word, p, t, note in ROWS:
        lines.append(f'| {e} | {what} | {word} ({where}) | {p} | {"—" if t is None else ("да" if t else "нет")} | {note} |')
    lines += ['', '## Что это говорит обо мне (по данным таблицы выше)',
              '- В целом я слегка самоуверен: средняя уверенность выше доли подтверждённых.',
              '- Уверенные предсказания в среднем держатся за счёт уже знакомых постановок (S1, S2, AUTO-02/03). Уверенные предсказания в новых постановках (EVO-02) не подтвердились ни разу.',
              '- «Скорее нет» ни разу не подтвердилось: там я был недостаточно уверен в отрицательном исходе. Скептицизм мне стоит выражать сильнее, 0,1–0,2, а не 0,3.',
              '- Правило (CLAUDE.md): предсказание в новой постановке без пилота записывать как «не знаю» (0,5), а не как уверенное.']
    open(os.path.join(ROOT, 'journal', 'SELF_CALIBRATION.md'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    if '--brief' in sys.argv:
        print(f'  моя калибровка: Брайер {brier:.3f} на {len(done)} предсказаниях, самообман {conf - hit:+.2f} (journal/SELF_CALIBRATION.md)')
