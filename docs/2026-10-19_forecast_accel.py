# Экстраполяция горизонта METR (50 %) от 17 ч в мае 2026 (t = 0) при ускорении.
# A: время удвоения 105 дн. и само сокращается вдвое каждые 2 года (как 2019–23 → 2024–26: ~210 → ~100 дн.).
# B: каждое следующее удвоение на 10 % (и 15 %) короче предыдущего (схема «суперэкспоненты»).
# C: постоянное удвоение 105 дн. (для сравнения).
import math, datetime as dt
H0, d0 = 17.0, 105 / 365.25                      # часы, годы
t0 = dt.date(2026, 5, 15)
WY = 2000.0                                      # часов в рабочем году
def date(t): return (t0 + dt.timedelta(days=round(t * 365.25))).strftime('%Y-%m')
def N_A(T): return (2 / math.log(2)) * (2 ** (T / 2) - 1) / d0
def N_C(T): return T / d0
def T_B(N, r): return d0 * (1 - r ** N) / (1 - r)
def T_A(N): return 2 * math.log2(1 + N * d0 * math.log(2) / 2)
print('сейчас (окт. 2026): A %.0f ч, C %.0f ч' % (H0 * 2 ** N_A(0.42), H0 * 2 ** N_C(0.42)))
for T in (1, 2, 3):
    print(f'{date(T)}: A {H0 * 2 ** N_A(T) / WY:,.1f} раб. лет; C {H0 * 2 ** N_C(T) / WY:,.2f} раб. лет')
targets = [('месяц', 167), ('год', WY), ('10 чел.-лет', 10 * WY), ('100 чел.-лет', 100 * WY), ('1000 чел.-лет', 1000 * WY)]
for name, h in targets:
    N = math.log2(h / H0)
    print(f'{name:>14}: удвоений {N:4.1f} | A {date(T_A(N))} | B10 {date(T_B(N, 0.9))} | B15 {date(T_B(N, 0.85))} | C {date(N * d0)}')
print('предел B10 (бесконечность):', date(d0 / 0.1), '| B15:', date(d0 / 0.15))
print(f'отставание горизонта при 80 % надёжности: множитель 5 = {math.log2(5):.1f} удвоения')
